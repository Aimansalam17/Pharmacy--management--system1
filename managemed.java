  // ===== Medicine class =====
    class Medicine {
        int id;
        String name;
        double price;
        int quantity;
        String category;

        Medicine(int id, String name, double price, int quantity, String category) {
            this.id = id;
            this.name = name;
            this.price = price;
            this.quantity = quantity;
            this.category = category;
        }
    }

    java.util.List<Medicine> medicines = new java.util.ArrayList<>();

    // ===== Constructor =====
    public managemed() {
        initComponents();
        setupTable();
        loadFromFile();
        refreshTable();
        setupTableClick();
    }

    // ===== Table setup =====
    void setupTable() {
        table1.setModel(new javax.swing.table.DefaultTableModel(
            new Object[][]{},
            new String[]{"ID", "Name", "Price", "Quantity", "Category"}
        ) {
            public boolean isCellEditable(int r, int c) {
                return false;
            }
        });
    }

    void refreshTable() {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) table1.getModel();
        model.setRowCount(0);

        for (Medicine m : medicines) {
            model.addRow(new Object[]{
                m.id, m.name, m.price, m.quantity, m.category
            });
        }
    }

    // ===== File handling =====
    void saveToFile() {
        try (java.io.PrintWriter pw =
                new java.io.PrintWriter(new java.io.FileWriter("medicine.txt"))) {

            for (Medicine m : medicines) {
                pw.println(m.id + "," + m.name + "," + m.price + ","
                        + m.quantity + "," + m.category);
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error saving file");
        }
    }

    void loadFromFile() {
        medicines.clear();
        java.io.File file = new java.io.File("medicine.txt");
        if (!file.exists()) return;

        try (java.util.Scanner sc = new java.util.Scanner(file)) {
            while (sc.hasNextLine()) {
                String[] p = sc.nextLine().split(",");
                if (p.length == 5) {
                    medicines.add(new Medicine(
                        Integer.parseInt(p[0]),
                        p[1],
                        Double.parseDouble(p[2]),
                        Integer.parseInt(p[3]),
                        p[4]
                    ));
                }
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading file");
        }
    }

    // ===== Table click =====
    void setupTableClick() {
        table1.addMouseListener(new java.awt.event.MouseAdapter() {
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int row = table1.getSelectedRow();
                if (row >= 0) {
                    txt1.setText(table1.getValueAt(row, 0).toString());
                    txt2.setText(table1.getValueAt(row, 1).toString());
                    txt3.setText(table1.getValueAt(row, 2).toString());
                    txt4.setText(table1.getValueAt(row, 3).toString());
                    box1.setSelectedItem(table1.getValueAt(row, 4).toString());
                }
            }
        });
    }

   
     

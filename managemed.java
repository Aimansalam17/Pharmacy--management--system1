    private void btn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn1ActionPerformed
        // TODO add your handling code here:
         try {
            int id = Integer.parseInt(txt1.getText().trim());
            String name = txt2.getText().trim();
            double price = Double.parseDouble(txt3.getText().trim());
            int qty = Integer.parseInt(txt4.getText().trim());
            String category = box1.getSelectedItem().toString();

            medicines.add(new Medicine(id, name, price, qty, category));
            refreshTable();
            saveToFile();

            javax.swing.JOptionPane.showMessageDialog(this, "Medicine added");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid input");
        }
    
    }//GEN-LAST:event_btn1ActionPerformed

    private void btn2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn2ActionPerformed
        // TODO add your handling code here:
             try {
            int id = Integer.parseInt(txt1.getText().trim());

            for (Medicine m : medicines) {
                if (m.id == id) {
                    m.name = txt2.getText().trim();
                    m.price = Double.parseDouble(txt3.getText().trim());
                    m.quantity = Integer.parseInt(txt4.getText().trim());
                    m.category = box1.getSelectedItem().toString();

                    refreshTable();
                    saveToFile();
                    javax.swing.JOptionPane.showMessageDialog(this, "Medicine updated");
                    return;
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Medicine ID not found");

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error updating");
        }
    
    }//GEN-LAST:event_btn2ActionPerformed


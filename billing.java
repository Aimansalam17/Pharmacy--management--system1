    class BillItem {
        int id;
        int qty;
        double price;
        double total;

        BillItem(int id, int qty, double price) {
            this.id = id;
            this.qty = qty;
            this.price = price;
            this.total = qty * price;
        }
    }

    java.util.List<BillItem> bills = new java.util.ArrayList<>();


    class Company {
        int id;
        String name;
        String address;
        String phone;
        String experience;

        Company(int id, String name, String address, String phone, String experience) {
            this.id = id;
            this.name = name;
            this.address = address;
            this.phone = phone;
            this.experience = experience;
        }
    }

    java.util.List<Company> companies = new java.util.ArrayList<>();


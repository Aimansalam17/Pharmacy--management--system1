    private void btn2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn2ActionPerformed
        // TODO add your handling code here:
          try {
            int id = Integer.parseInt(txt1.getText().trim());

            for (Company c : companies) {
                if (c.id == id) {
                    c.name = txt2.getText().trim();
                    c.address = txt3.getText().trim();
                    c.phone = txt4.getText().trim();
                    c.experience = txt5.getText().trim();

                    refreshTable();
                    saveToFile();
                    javax.swing.JOptionPane.showMessageDialog(this, "Company updated");
                    return;
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Company ID not found");

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error updating");
        }
    
    }//GEN-LAST:event_btn2ActionPerformed

    private void btn3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn3ActionPerformed
        // TODO add your handling code here:
         try {
            int id = Integer.parseInt(txt1.getText().trim());
            boolean removed = companies.removeIf(c -> c.id == id);

            if (removed) {
                refreshTable();
                saveToFile();
                javax.swing.JOptionPane.showMessageDialog(this, "Company deleted");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Company ID not found");
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting");
        }
    

    }//GEN-LAST:event_btn3ActionPerformed

